#!/usr/bin/env python3
"""Build a unified index of every example recipe in the KB.

Sources indexed:
  kb/examples/labs/**          Workato Labs sample apps (MIT)
  kb/examples/workspace/**     recipes exported from our own workspace
  kb/community/recipes/**      community-library recipes (public, redacted)
  kb/patterns/workato-labs/**/templates/*.json   Labs skill templates (MIT)

Output:
  kb/examples/index.json   [{path, source, name, trigger, steps[], keywords[], features[], copies}]
  kb/examples/INDEX.md     human-readable summary: coverage by step and by feature

Query with:  python3 kb/search.py --examples salesforce.search_sobjects [--feature try]
"""
from __future__ import annotations

import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_JSON = ROOT / "kb" / "examples" / "index.json"
OUT_MD = ROOT / "kb" / "examples" / "INDEX.md"
CONTROL = {"if", "elsif", "else", "try", "catch", "foreach", "repeat", "while_condition", "stop"}


def load(p: Path):
    try:
        d = json.loads(p.read_text())
    except Exception:
        return None
    if not isinstance(d, dict):
        return None
    code = d.get("code")
    if isinstance(code, str):
        try:
            code = json.loads(code)
        except Exception:
            return None
    if not (isinstance(code, dict) and code.get("keyword") == "trigger"):
        return None
    return d, code


def walk(block: dict, steps: list, features: set) -> None:
    kw = block.get("keyword")
    if kw in CONTROL:
        features.add(kw)
    if kw in ("trigger", "action") and block.get("provider"):
        steps.append(f"{block['provider']}.{block.get('name')}")
        if block.get("name") == "__adhoc_http_action":
            features.add("custom_http")
    s = json.dumps(block.get("input") or {})
    if "_dp(" in s:
        features.add("datapill_dp")
    if "_('data." in s:
        features.add("datapill_legacy")
    if '"=' in s:
        features.add("formula")
    for child in block.get("block") or []:
        if isinstance(child, dict):
            walk(child, steps, features)


def source_of(p: Path) -> str:
    rel = p.relative_to(ROOT).as_posix()
    if rel.startswith("kb/community/"):
        return "community"
    if rel.startswith("kb/examples/workspace/"):
        return "workspace"
    if rel.startswith("kb/patterns/"):
        return "labs-template"
    return "labs-sample"


def main() -> None:
    files = (list((ROOT / "kb/examples/labs").rglob("*.json")) + list((ROOT / "kb/examples/workspace").rglob("*.json"))
             + list((ROOT / "kb/community/recipes").rglob("*.json"))
             + list((ROOT / "kb/patterns/workato-labs").rglob("templates/*.json")))
    rows = []
    for p in sorted(files):
        r = load(p)
        if not r:
            continue
        d, code = r
        steps: list[str] = []
        features: set[str] = set()
        walk(code, steps, features)
        rows.append({
            "path": p.relative_to(ROOT).as_posix(),
            "source": source_of(p),
            "name": d.get("name") or p.stem,
            "trigger": steps[0] if steps else None,
            "steps": list(dict.fromkeys(steps)),
            "features": sorted(features),
            "copies": d.get("copy_count") or 0,
        })
    OUT_JSON.write_text(json.dumps(rows, indent=1, ensure_ascii=False) + "\n")

    by_src = collections.Counter(r["source"] for r in rows)
    by_step = collections.Counter(s for r in rows for s in r["steps"])
    by_feat = collections.Counter(f for r in rows for f in r["features"])
    by_prov = collections.Counter(s.split(".")[0] for r in rows for s in set(r["steps"]))
    md = ["# Example recipe index", "",
          f"{len(rows)} complete recipe examples: " + ", ".join(f"{k} {v}" for k, v in by_src.most_common()) + ".",
          "Generated by `kb/examples/build_index.py`. Query: `python3 kb/search.py --examples <provider.action> [--feature try]`.",
          "", "## Features", "", "| Feature | Recipes |", "| --- | ---: |"]
    md += [f"| `{k}` | {v} |" for k, v in by_feat.most_common()]
    md += ["", "## Providers (recipes using each)", "", ", ".join(f"`{k}` {v}" for k, v in by_prov.most_common())]
    md += ["", "## Most common steps", "", "| Step | Recipes |", "| --- | ---: |"]
    md += [f"| `{k}` | {v} |" for k, v in by_step.most_common(150)]
    OUT_MD.write_text("\n".join(md) + "\n")
    print(f"indexed {len(rows)} examples ({dict(by_src)}), {len(by_step)} distinct steps, {len(by_prov)} providers")


if __name__ == "__main__":
    main()
